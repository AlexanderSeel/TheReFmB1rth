"""Position-stable wrapper for the real-hardware RB240 polish pass."""
from __future__ import annotations
import argparse
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("rb240_polish_v2", ROOT / "tools" / "apply_rb240_physical_polish_v2.py")
V2 = importlib.util.module_from_spec(SPEC)
assert SPEC and SPEC.loader
SPEC.loader.exec_module(V2)


def one(text: str, old: str, new: str, label: str) -> str:
    n = text.count(old)
    if n != 1:
        raise SystemExit(f"physical-polish-v3 anchor mismatch ({label}): expected 1, got {n}")
    return text.replace(old, new, 1)


def patch_bridge(root: Path) -> None:
    p = root / "firmware" / "refm" / "integration" / "refm_felucca_bridge.c"
    t = p.read_text()
    t = one(t, "static uint8_t g_focus_region;\n",
            "static uint8_t g_focus_region;\nstatic uint8_t g_hold;\n", "hold storage")

    # Earlier overlays now contain several g_focus_active resets. Restrict HOLD
    # initialization to the explicit bridge init function so this pass remains
    # stable when focus-exit/panic helpers evolve.
    ia = t.find("void refm_felucca_init(uint16_t bpm)\n{")
    ib = t.find("\n}\n", ia)
    if ia < 0 or ib < 0:
        raise SystemExit("physical-polish-v3 explicit init function not found")
    init_chunk = t[ia:ib]
    init_anchor = "    g_focus_active = 0u;\n"
    if init_chunk.count(init_anchor) != 1:
        raise SystemExit(
            f"physical-polish-v3 init focus anchor mismatch: expected 1, got {init_chunk.count(init_anchor)}"
        )
    init_chunk = init_chunk.replace(init_anchor, init_anchor + "    g_hold = 0u;\n", 1)
    t = t[:ia] + init_chunk + t[ib:]

    t = one(t,
'''static void cycle_machine_context(int8_t delta)
{
    ui240_machine_t next;
    if (!delta) return;
    if (g_ui.page == UI240_ACID_MAIN || g_ui.page == UI240_ACID_STEP) {
''',
'''static void cycle_machine_context(int8_t delta)
{
    ui240_machine_t next;
    if (!delta) return;
    if (g_ui.page == UI240_HOME) {
        int m = (int)g_ui.machine + (delta < 0 ? -1 : 1);
        if (m < 0) m = 3;
        if (m > 3) m = 0;
        refm_felucca_panic();
        ui240_set_machine(&g_ui, (ui240_machine_t)m);
    } else if (g_ui.page == UI240_ACID_MAIN || g_ui.page == UI240_ACID_STEP) {
''', "HOME machine select")

    t = one(t,
        "        if (encoder > REFM_ENC_K4) continue;\n"
        "        if (g_ui.page == UI240_ACID_MAIN) ui240_edit_acid_main(&g_ui, &g_refm.groovebox, encoder, d);\n",
        "        if (encoder > REFM_ENC_K4) continue;\n"
        "        if (g_ui.page == UI240_HOME) {\n"
        "            if (g_ui.machine < UI240_MACHINE_808) ui240_edit_acid_main(&g_ui, &g_refm.groovebox, encoder, d);\n"
        "            else ui240_edit_mixer(&g_ui, &g_refm.groovebox, encoder, d);\n"
        "        } else if (g_ui.page == UI240_ACID_MAIN) ui240_edit_acid_main(&g_ui, &g_refm.groovebox, encoder, d);\n",
        "HOME live knobs")

    # Insert HOLD suppression by function position rather than depending on an
    # exact intermediate performance-key return generated by earlier overlays.
    a = t.find("void refm_felucca_key_event(")
    b = t.find("\n}\n", a)
    if a < 0 or b < 0:
        raise SystemExit("physical-polish-v3 key-event function not found")
    chunk = t[a:b]
    needle = "    status = (uint8_t)((on ? 0x90u : 0x80u) | g_ui.machine);\n"
    if needle not in chunk:
        raise SystemExit("physical-polish-v3 key-event status anchor missing")
    chunk = chunk.replace(needle,
        "    if (!on && g_hold && (g_ui.page == UI240_HOME || g_ui.page == UI240_ACID_MAIN)) return;\n" + needle, 1)
    t = t[:a] + chunk + t[b:]

    t = one(t,
'''    case REFM_ACT_ALT:
        if (g_ui.page == UI240_ACID_STEP && g_ui.machine < UI240_MACHINE_808)
            ui240_toggle_acid_flag(&g_ui, g, SEQ16_SLIDE);
''',
'''    case REFM_ACT_ALT:
        if (g_ui.page == UI240_HOME || g_ui.page == UI240_ACID_MAIN) {
            g_hold ^= 1u;
            if (!g_hold) refm_felucca_panic();
        } else if (g_ui.page == UI240_ACID_STEP && g_ui.machine < UI240_MACHINE_808)
            ui240_toggle_acid_flag(&g_ui, g, SEQ16_SLIDE);
''', "REC HOLD action")
    t = one(t, "    case 35: return g_focus_region;\n    default: return 0u;\n",
            "    case 35: return g_focus_region;\n    case 36: return g_hold;\n    default: return 0u;\n",
            "HOLD readback")
    p.write_text(t)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("felucca", type=Path)
    args = ap.parse_args()
    root = args.felucca.resolve()
    if not (root / ".refm-rb240-full-parity").is_file():
        raise SystemExit("apply full RB-240 parity first")
    patch_bridge(root)
    V2.patch_performance(root)
    V2.patch_leds(root)
    V2.patch_draw(root)
    (root / ".refm-rb240-physical-polish").write_text(
        "home=machine-select+live-knobs+drum-audition\n"
        "leds=refm-page-aware\nhold=rec-latch\nseq=keyboard-visible\n"
        "drum-footer=unclipped\n808=black\n909=grey\nacid=silver\n"
        "machine-switch=no-full-lcd-clear\n")
    print("RB-240 hardware screenshot polish v3 applied")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
